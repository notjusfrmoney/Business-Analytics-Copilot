from __future__ import annotations

import json
import math
import sys
from dataclasses import dataclass
from datetime import date, datetime
from decimal import Decimal
from pathlib import Path
from typing import Any, Iterable

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

QUESTIONS_PATH = ROOT / "evaluation" / "questions.json"
EXPECTED_RESULTS_PATH = ROOT / "evaluation" / "expected_results.json"
DEFAULT_DATABASE_PATH = ROOT / "data" / "processed" / "business_analytics.duckdb"


@dataclass(frozen=True)
class DataFrameComparison:
    matches: bool
    reason: str


def load_questions(path: str | Path = QUESTIONS_PATH) -> list[dict[str, Any]]:
    with Path(path).open(encoding="utf-8") as source:
        questions = json.load(source)
    if not isinstance(questions, list):
        raise ValueError("The benchmark questions file must contain a JSON array.")

    identifiers: set[str] = set()
    for question in questions:
        if not isinstance(question, dict):
            raise ValueError("Each benchmark question must be a JSON object.")
        identifier = question.get("id")
        prompt = question.get("question")
        answerable = question.get("answerable")
        if not isinstance(identifier, str) or not identifier.strip():
            raise ValueError("Each benchmark question must have a non-empty id.")
        if identifier in identifiers:
            raise ValueError(f"Duplicate benchmark question id: {identifier}.")
        identifiers.add(identifier)
        if not isinstance(prompt, str) or not prompt.strip():
            raise ValueError(f"Question {identifier} has no question text.")
        if not isinstance(answerable, bool):
            raise ValueError(f"Question {identifier} must specify answerable as a boolean.")
        if answerable and not isinstance(question.get("expected_sql"), str):
            raise ValueError(f"Answerable question {identifier} must specify expected_sql.")
        if not answerable and not isinstance(question.get("expected_reason"), str):
            raise ValueError(f"Unsupported question {identifier} must specify expected_reason.")
    return questions


def load_expected_results(
    path: str | Path = EXPECTED_RESULTS_PATH,
) -> dict[str, dict[str, Any]]:
    with Path(path).open(encoding="utf-8") as source:
        payload = json.load(source)
    results = payload.get("results") if isinstance(payload, dict) else None
    if not isinstance(results, dict):
        raise ValueError("Expected results must contain a 'results' object.")
    return results


def generate_expected_results(
    *,
    database_path: str | Path = DEFAULT_DATABASE_PATH,
    questions_path: str | Path = QUESTIONS_PATH,
    output_path: str | Path = EXPECTED_RESULTS_PATH,
) -> dict[str, dict[str, Any]]:
    """Execute benchmark ground-truth SQL and persist results as JSON."""
    from src.database.duckdb_manager import DuckDBManager

    database_file = Path(database_path)
    if not database_file.is_file():
        raise FileNotFoundError(
            f"Sample DuckDB database not found: {database_file}. "
            "Run tests/test_data_foundation.py to build it from the sample CSVs."
        )

    results: dict[str, dict[str, Any]] = {}
    with DuckDBManager(database_file) as database:
        for item in load_questions(questions_path):
            if not item["answerable"]:
                continue
            dataframe = database.execute_query(item["expected_sql"])
            results[item["id"]] = {
                "columns": [str(column) for column in dataframe.columns],
                "rows": _json_safe(dataframe.to_dict(orient="records")),
            }

    payload = {
        "source_database": _relative_or_absolute(database_file),
        "description": (
            "Expected rows generated by executing each question's expected_sql "
            "against the deterministic sample DuckDB database."
        ),
        "results": results,
    }
    output_file = Path(output_path)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    output_file.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False, allow_nan=False) + "\n",
        encoding="utf-8",
    )
    return results


def compare_dataframes(
    expected: pd.DataFrame,
    actual: pd.DataFrame,
    *,
    absolute_tolerance: float = 0.01,
    relative_tolerance: float = 0.001,
    ordered_rows: bool = False,
    ordered_columns: bool = False,
) -> DataFrameComparison:
    """Compare values with numeric tolerance and optional ordering requirements."""
    if expected.empty and actual.empty:
        if _columns_match(expected.columns, actual.columns, ordered_columns):
            return DataFrameComparison(True, "Both results are empty.")
        return DataFrameComparison(False, "Empty result columns differ.")
    if expected.shape != actual.shape:
        return DataFrameComparison(
            False,
            f"Shape differs: expected {expected.shape}, got {actual.shape}.",
        )
    if not _columns_match(expected.columns, actual.columns, ordered_columns):
        return DataFrameComparison(
            False,
            f"Columns differ: expected {list(expected.columns)}, got {list(actual.columns)}.",
        )

    actual_aligned = actual.copy()
    actual_by_name = {str(column).casefold(): column for column in actual.columns}
    actual_aligned = actual_aligned[
        [actual_by_name[str(column).casefold()] for column in expected.columns]
    ]
    if ordered_rows:
        for row_number in range(len(expected)):
            if not _rows_match(
                expected.iloc[row_number].tolist(),
                actual_aligned.iloc[row_number].tolist(),
                absolute_tolerance,
                relative_tolerance,
            ):
                return DataFrameComparison(False, f"Values differ at row {row_number}.")
    else:
        unmatched_actual = list(range(len(actual_aligned)))
        for _, expected_row in expected.iterrows():
            match_index = next(
                (
                    index
                    for index in unmatched_actual
                    if _rows_match(
                        expected_row.tolist(),
                        actual_aligned.iloc[index].tolist(),
                        absolute_tolerance,
                        relative_tolerance,
                    )
                ),
                None,
            )
            if match_index is None:
                return DataFrameComparison(False, "One or more expected rows were not found.")
            unmatched_actual.remove(match_index)
    return DataFrameComparison(True, "Results match within configured tolerances.")


def _columns_match(
    expected: Iterable[object],
    actual: Iterable[object],
    ordered: bool,
) -> bool:
    expected_names = [str(column).casefold() for column in expected]
    actual_names = [str(column).casefold() for column in actual]
    return expected_names == actual_names if ordered else set(expected_names) == set(actual_names)


def _rows_match(
    expected: list[Any],
    actual: list[Any],
    absolute_tolerance: float,
    relative_tolerance: float,
) -> bool:
    return len(expected) == len(actual) and all(
        _values_match(left, right, absolute_tolerance, relative_tolerance)
        for left, right in zip(expected, actual)
    )


def _values_match(
    expected: Any,
    actual: Any,
    absolute_tolerance: float,
    relative_tolerance: float,
) -> bool:
    if _is_missing(expected) or _is_missing(actual):
        return _is_missing(expected) and _is_missing(actual)
    if _is_number(expected) and _is_number(actual):
        return math.isclose(
            float(expected),
            float(actual),
            abs_tol=absolute_tolerance,
            rel_tol=relative_tolerance,
        )
    return str(expected) == str(actual)


def _is_missing(value: Any) -> bool:
    try:
        return bool(pd.isna(value))
    except (TypeError, ValueError):
        return False


def _is_number(value: Any) -> bool:
    return (
        isinstance(value, (int, float, Decimal, np.integer, np.floating))
        and not isinstance(value, (bool, np.bool_))
        and math.isfinite(float(value))
    )


def _json_safe(value: Any) -> Any:
    if isinstance(value, dict):
        return {str(key): _json_safe(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_safe(item) for item in value]
    if value is None or value is pd.NA:
        return None
    if isinstance(value, (bool, np.bool_)):
        return bool(value)
    if isinstance(value, (int, np.integer)):
        return int(value)
    if isinstance(value, (float, np.floating, Decimal)):
        number = float(value)
        return number if math.isfinite(number) else None
    if isinstance(value, (pd.Timestamp, datetime, date)):
        return value.isoformat()
    if _is_missing(value):
        return None
    return value


def _relative_or_absolute(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(ROOT.resolve())).replace("\\", "/")
    except ValueError:
        return str(path.resolve())
